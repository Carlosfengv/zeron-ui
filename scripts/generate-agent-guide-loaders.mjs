import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export async function generateAgentGuideLoaders({ check = false } = {}) {
  const keys = [];
  for (const collection of ["blocks", "components"]) {
    for (const entry of (await readdir(path.join(root, "docs/agent-guides", collection), { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
      if (!entry.isFile() || !/^[a-z0-9-]+\.md$/.test(entry.name)) throw new Error(`Unexpected guide entry: ${collection}/${entry.name}`);
      keys.push(`${collection}/${entry.name}`);
    }
  }
  const content = `// Generated by scripts/generate-agent-guide-loaders.mjs.\nimport { readFile } from "node:fs/promises";\nimport { join } from "node:path";\n\nexport const agentGuideLoaders: Record<string, () => Promise<string>> = {\n${keys.map((key) => `  "${key}": () => readFile(join(process.cwd(), "docs/agent-guides/${key}"), "utf8"),`).join("\n")}\n};\n`;
  const target = path.join(root, "docs/generated/agent-guide-loaders.generated.ts");
  if (check) {
    if (await readFile(target, "utf8").catch(() => null) !== content) throw new Error("Agent guide loaders are stale; run pnpm agents:guides:build");
  } else await writeFile(target, content);
  return keys;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const keys = await generateAgentGuideLoaders({ check: process.argv.includes("--check") });
  console.log(`Agent guide loaders: ${keys.length} guides`);
}
