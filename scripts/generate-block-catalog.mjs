import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repository = fileURLToPath(new URL("../", import.meta.url));
const output = "packages/blocks/src/catalog.ts";

async function docCopy(root, locale, slug) {
  const file = `docs/content/${locale}/blocks/${slug}.json`;
  const messages = JSON.parse(await readFile(join(root, file), "utf8"));
  const candidates = Object.entries(messages).filter(([, value]) =>
    typeof value?.title === "string" && value.title.trim() &&
    typeof value?.description === "string" && value.description.trim());
  // Some docs also ship a preview namespace with its own title and description.
  const sections = candidates.length > 1 ? candidates.filter(([key]) => key.endsWith("Block")) : candidates;
  if (sections.length !== 1) throw new Error(`Expected one Block title and description in ${file}`);
  const { title, description } = sections[0][1];
  return { title, description };
}

const inlineEntry = entry => `  { ${Object.entries(entry).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join(", ")} },`;

export async function generateBlockCatalog({ root = repository, check = false } = {}) {
  const readJson = async file => JSON.parse(await readFile(join(root, file), "utf8"));
  const [{ items }, capabilities, aliases] = await Promise.all([
    readJson("packages/blocks/registry.json"),
    readJson("packages/blocks/block-capabilities.json"),
    readJson("docs/catalog/block-registry-slugs.json"),
  ]);
  const blocks = items.filter(item => item.type === "registry:block");
  const names = new Set(blocks.map(item => item.name));
  if (names.size !== blocks.length) throw new Error("Duplicate Block name in packages/blocks/registry.json");
  for (const name of [...Object.keys(aliases), ...Object.keys(capabilities)]) {
    if (!names.has(name)) throw new Error(`Unknown Block in slug or capability manifest: ${name}`);
  }
  const slugs = new Set();
  const entries = await Promise.all(blocks.map(async ({ name, categories, registryDependencies = [], dependencies = [] }) => {
    const capability = capabilities[name];
    if (!capability || !["react", "next"].includes(capability.framework) || !["data-block", "template"].includes(capability.kind)) {
      throw new Error(`Missing or invalid installation capability for Block: ${name}`);
    }
    const slug = aliases[name] ?? name;
    if (typeof slug !== "string" || !/^[a-z0-9-]+$/.test(slug) || slugs.has(slug)) throw new Error(`Invalid or duplicate docs slug for Block: ${name}`);
    slugs.add(slug);
    if (!Array.isArray(categories) || !categories.length) throw new Error(`Missing Registry categories for Block: ${name}`);
    const [chinese, english] = await Promise.all([docCopy(root, "zh-CN", slug), docCopy(root, "en", slug)]);
    return {
      name,
      ...(slug === name ? {} : { slug }),
      ...chinese,
      categories,
      dependencies: [...new Set([...registryDependencies, ...dependencies])],
      installation: { framework: capability.framework, kind: capability.kind },
      english,
    };
  }));
  const source = `// Generated by scripts/generate-block-catalog.mjs. Run pnpm catalog:build to update.
export type BlockFramework = "react" | "next";
export type BlockInstallationKind = "data-block" | "template";

export interface BlockCapability {
  framework: BlockFramework;
  kind: BlockInstallationKind;
}

const blockCatalogEntries = [
${entries.map(inlineEntry).join("\n")}
] as const;

export const blockCatalog = blockCatalogEntries.map(({ english: _english, ...block }) => block);

export function getBlockCapability(name: string): BlockCapability {
  const block = blockCatalogEntries.find(entry => entry.name === name);
  if (!block) throw new Error(\`Missing installation capability for Block: \${name}\`);
  return block.installation;
}

export function getBlockCatalogCopy(name: string, locale: "en" | "zh-CN") {
  const block = blockCatalogEntries.find(entry => entry.name === name);
  if (!block) return undefined;
  return locale === "en" ? block.english : { title: block.title, description: block.description };
}
`;
  const target = join(root, output);
  const current = await readFile(target, "utf8").catch(error => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (current !== source) {
    if (check) throw new Error(`${output} is stale; run pnpm catalog:build`);
    await writeFile(target, source);
  }
  return entries.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const count = await generateBlockCatalog({ check });
  console.log(`${check ? "Checked" : "Generated"} the catalog for ${count} Blocks.`);
}
