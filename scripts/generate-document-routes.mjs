import { mkdir, readFile, readdir, rm, rmdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const root = process.cwd();
const routeRoot = join(root, "app/[locale]/docs");
const check = process.argv.includes("--check");
const manifest = await readFile(join(root, "docs/manifest.ts"), "utf8");
const collectionSource = await readFile(join(root, "docs/catalog/artifact-collections.ts"), "utf8");
const pageSlugs = new Set(
  [...collectionSource.matchAll(/^  "([\w-]+)",$/gm)].map((match) => match[1]),
);
const entries = new Map();
const generatedHeader = "// Generated by scripts/generate-document-routes.mjs.";

for (const match of manifest.matchAll(/^  (entry|blockEntry)\(\{ slug: "([\w-]+)"/gm)) {
  const [, type, slug] = match;
  const collection = type === "entry" ? "components" : pageSlugs.has(slug) ? "pages" : "blocks";
  const key = `${type === "entry" ? "components" : "blocks"}/${slug}`;
  if (entries.has(key)) throw new Error(`Duplicate manifest entry: ${key}`);
  entries.set(key, collection);
}

if (!entries.size) throw new Error("No documentation entries found; check the manifest format.");

const expected = new Map();
for (const sourceCollection of ["components", "blocks"]) {
  const source = await readFile(join(root, `docs/generated/${sourceCollection === "components" ? "component" : "block"}-page-loaders.generated.ts`), "utf8");
  for (const match of source.matchAll(/^  "([\w-]+)\/([\w-]+)": \(\) => import\("(@docs\/pages\/[\w/-]+\/page)"\),$/gm)) {
    const [, keyCollection, slug, importPath] = match;
    if (keyCollection !== sourceCollection) throw new Error(`Unexpected doc loader: ${match[0]}`);
    const collection = entries.get(`${sourceCollection}/${slug}`);
    if (!collection) throw new Error(`Doc loader is missing from the manifest: ${sourceCollection}/${slug}`);
    const path = join(routeRoot, collection, "(detail)", slug, "page.tsx");
    if (expected.has(path)) throw new Error(`Duplicate doc loader: ${sourceCollection}/${slug}`);
    expected.set(path, `// Generated by scripts/generate-document-routes.mjs.\nimport { setRequestLocale } from "next-intl/server";\nimport { assertLocale } from "@/app/_i18n/locale";\nimport { generateDocMetadata, renderStaticDocPage } from "@docs/server/render-page";\n\ntype Props = { params: Promise<{ locale: string }> };\n\nexport async function generateMetadata({ params }: Props) {\n  const { locale } = await params;\n  assertLocale(locale);\n  return generateDocMetadata({ locale, collection: "${collection}", slug: "${slug}" });\n}\n\nexport default async function DocumentationPage({ params }: Props) {\n  const { locale } = await params;\n  assertLocale(locale);\n  setRequestLocale(locale);\n  return renderStaticDocPage({ locale, collection: "${collection}", slug: "${slug}", loadPage: () => import("${importPath}") });\n}\n`);
  }
}

if (expected.size !== entries.size) {
  const missing = [...entries.keys()].filter((key) => {
    const [, slug] = key.split("/");
    const collection = entries.get(key);
    return !expected.has(join(routeRoot, collection, "(detail)", slug, "page.tsx"));
  });
  throw new Error(`Manifest entries have no doc loaders: ${missing.join(", ")}`);
}

const staleRoutes = [];
for (const collection of ["components", "blocks", "pages"]) {
  const detailRoot = join(routeRoot, collection, "(detail)");
  for (const slug of await readdir(detailRoot).catch(() => [])) {
    if (slug === "layout.tsx" || slug === "loading.tsx") continue;
    const path = join(detailRoot, slug, "page.tsx");
    if (expected.has(path)) continue;
    const content = await readFile(path, "utf8").catch(() => "");
    if (!content.startsWith(generatedHeader)) continue;
    if (check) throw new Error(`Stale generated route: ${path}`);
    staleRoutes.push(path);
  }
}

const updates = [];
for (const [path, content] of expected) {
  const current = await readFile(path, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (current === content) continue;
  if (check) throw new Error(`Generated route is stale: ${path}`);
  if (current !== null && !current.startsWith(generatedHeader)) {
    throw new Error(`Refusing to overwrite a handwritten route: ${path}`);
  }
  updates.push([path, content]);
}

for (const path of staleRoutes) {
  await rm(path);
  if ((await readdir(dirname(path))).length === 0) await rmdir(dirname(path));
}

for (const [path, content] of updates) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

console.log(`${check ? "Checked" : "Generated"} ${expected.size} split documentation routes.`);
