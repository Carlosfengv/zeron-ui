import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { previewSourceFiles } from "./preview-source-allowlist.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export async function generatePreviewSources(root = repositoryRoot, check = false) {
  const expected = new Map();
  const references = {};
  for (const [slug, files] of Object.entries(previewSourceFiles)) {
    if (!files.length || files.some((file) => !/^packages\/blocks\/src\/[a-z0-9/-]+\.(?:tsx?|jsx?)$/.test(file))) {
      throw new Error(`Invalid preview source allowlist entry: ${slug}`);
    }
    const contents = (await Promise.all(files.map((file) => readFile(path.join(root, file), "utf8")))).join("\n\n");
    const hash = createHash("sha256").update(contents).digest("hex");
    const filename = `${hash}.txt`;
    expected.set(path.join(root, "public/docs-source", filename), contents);
    references[slug] = { url: `/docs-source/${filename}` };
  }

  const manifest = `// Generated by scripts/generate-preview-sources.mjs. Do not edit.\nimport type { PreviewSourceReference } from "./preview-source";\n\nconst blockPreviewSources = ${JSON.stringify(references, null, 2)} as const satisfies Record<string, PreviewSourceReference>;\n\nexport function getBlockPreviewSource(slug: keyof typeof blockPreviewSources): PreviewSourceReference {\n  return blockPreviewSources[slug];\n}\n\n/** Exact known assets only: missing hashes must never receive immutable caching. */\nexport function getPreviewSourceAssetUrls(): string[] {\n  return [...new Set(Object.values(blockPreviewSources).map(({ url }) => url))];\n}\n`;
  expected.set(path.join(root, "docs/lib/block-preview-sources.generated.ts"), manifest);

  const assetRoot = path.join(root, "public/docs-source");
  for (const filename of await readdir(assetRoot).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  })) {
    const location = path.join(assetRoot, filename);
    if (expected.has(location)) continue;
    if (check) throw new Error(`Stale preview source asset: ${filename}`);
    if (!/^[a-f0-9]{64}\.txt$/.test(filename)) throw new Error(`Unexpected preview source asset: ${filename}`);
    await rm(location);
  }

  for (const [location, contents] of expected) {
    const current = await readFile(location, "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (current === contents) continue;
    if (check) throw new Error(`Generated preview source is stale: ${path.relative(root, location)}`);
    await mkdir(path.dirname(location), { recursive: true });
    await writeFile(location, contents);
  }
  return Object.keys(references).length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const count = await generatePreviewSources(repositoryRoot, check);
  console.log(`${check ? "Checked" : "Generated"} ${count} allowlisted preview sources.`);
}
